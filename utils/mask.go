package utils

import "strings"

// Маскировка имён для показа одному пользователю другого.
//
// Раньше кабинет отдавал реферальный список с полными username и email, а
// звёздочки рисовал уже браузер. Это не скрывало ничего: настоящие адреса
// лежали в JSON и читались в devtools первым же F12. Поэтому маскировка живёт
// на сервере — наружу уходит только то, что можно показать.
//
// Обе функции идемпотентны: повторная маскировка уже замаскированного значения
// его не меняет. Это важно, потому что клиент какое-то время будет продолжать
// прогонять пришедшую строку через свою старую защиту.

// MaskEdges оставляет первый и последний символы: «ivan_k» → «i***k».
//
// Считаем в рунах, а не в байтах: имя «Александр» в байтовой нарезке
// развалилось бы посреди символа.
func MaskEdges(input string) string {
	s := strings.TrimSpace(input)
	if s == "" {
		return ""
	}
	// Уже замаскированное значение не трогаем: иначе повторный прогон
	// «a***» дал бы «a****», и строка росла бы с каждым проходом.
	if strings.Contains(s, "***") {
		return s
	}
	r := []rune(s)
	if len(r) <= 1 {
		return s + "***"
	}
	return string(r[0]) + "***" + string(r[len(r)-1])
}

// MaskEmail прячет локальную часть, оставляя домен: «ivan@mail.ru» → «i***n@mail.ru».
//
// Домен виден намеренно: он не опознаёт человека, но объясняет, что это вообще
// почта, а не обрубок ника.
func MaskEmail(input string) string {
	s := strings.ToLower(strings.TrimSpace(input))
	at := strings.LastIndex(s, "@")
	if at <= 0 || at >= len(s)-1 {
		return MaskEdges(s)
	}
	return MaskEdges(s[:at]) + "@" + s[at+1:]
}
