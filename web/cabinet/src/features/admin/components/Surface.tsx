import type { HTMLAttributes } from 'react'

import { cn } from '@/lib/utils'

/**
 * Шкала поверхностей админки.
 *
 * Проблема, ради которой это заведено: карточка лежала на карточке того же
 * цвета, а у половины контролов фона не было вовсе — только рамка. Токены для
 * шкалы в `index.css` разведены по светлоте с самого начала («фон → muted →
 * card → secondary → border»), но компоненты брали их вразнобой: один
 * `bg-muted` встречался в девяти прозрачностях, и ни одна не значила «такой-то
 * уровень» — каждая подбиралась на глаз под свой экран.
 *
 * Уровней три, и выбирается уровень не по вкусу, а по роли элемента:
 *
 *  - `well` — то, во что вводят или откуда читают: поля, редакторы, блоки
 *    read-only значений. Утоплено ниже карточки.
 *  - `card` — плоскость: карточка, панель модалки, секция настроек. База, от
 *    которой считаются остальные.
 *  - `raised` — то, на что нажимают, и вложенный блок внутри карточки: кнопки,
 *    кликабельные ряды, карточки в модалке. Поднято выше карточки.
 *
 * Главное правило: ничто не лежит на поверхности своего же уровня. Вложил блок
 * в карточку — подними или утопи; совпадение уровней читается как отсутствие
 * элемента. Разрыв между соседями всего 2–6% светлоты, поэтому пара
 * «утопленное поле + поднятая кнопка» разведена на два шага и видна, а два
 * `card` подряд — нет.
 *
 * Прозрачность здесь не участвует: она означает состояние (`hover:bg-accent/40`),
 * а не уровень. Нужен другой фон — берите соседний уровень, а не дробь от этого.
 *
 * Правила целиком — `documentation/cabinet/surfaces.md`.
 */
export type SurfaceLevel = 'well' | 'card' | 'raised'

/** Только заливка — для элемента внутри уже обведённого контейнера. */
const BG: Record<SurfaceLevel, string> = {
  well: 'bg-muted',
  card: 'bg-card',
  raised: 'bg-secondary',
}

/*
 * Рамка идёт в комплекте с уровнем, а не подбирается отдельно.
 * У `raised` она непрозрачная: это контрол, его край должен быть виден. У
 * плоскостей приглушена — там рамка разделяет, а не очерчивает нажимаемое.
 */
const EDGE: Record<SurfaceLevel, string> = {
  well: 'border border-border/50',
  card: 'border border-border/60',
  raised: 'border border-border',
}

/** Заливка и рамка уровня. Основной способ: `className={surface('raised', 'rounded-lg p-3')}`. */
export function surface(level: SurfaceLevel, className?: string): string {
  return cn(BG[level], EDGE[level], className)
}

/** Одна заливка, без рамки — когда элемент уже внутри обведённого контейнера. */
export function surfaceBg(level: SurfaceLevel, className?: string): string {
  return cn(BG[level], className)
}

/**
 * Готовый контейнер для обычного блока. Для кнопок, списков и всего, у чего
 * свой тег и свои пропсы, берите `surface()` — обёртка того не стоит.
 */
export function Surface({
  level,
  className,
  ...rest
}: { level: SurfaceLevel } & HTMLAttributes<HTMLDivElement>) {
  return <div className={surface(level, className)} {...rest} />
}
